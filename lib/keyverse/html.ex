  @doc false
  def passage_strip_html(%Scope{kind: kind, parsed: p} = scope)
      when kind in ["verse", "range"] and is_map(p) do
    book = p.book
    chapter = p.chapter
    v0 = p.verse
    v1 = p.verse_end || v0

    if is_binary(book) and is_integer(chapter) and is_integer(v0) do
      case Keyverse.TextCache.get_chapter(book, chapter) do
        {:ok, doc} ->
          rows =
            (doc["verses"] || [])
            |> Enum.filter(fn row ->
              v = row_verse_num(row)
              is_integer(v) and v >= v0 and v <= v1
            end)

          if rows == [] do
            ""
          else
            body =
              Enum.map_join(rows, "\n", fn row ->
                v = row_verse_num(row)
                t = to_string(row["text"] || row["t"] || "")

                ~s(<p class="passage-v" data-v="#{v}"><sup class="passage-vn">#{v}</sup>) <>
                  esc(t) <> "</p>"
              end)

            """
            <section class="passage-strip" aria-label="#{esc(Scope.display(scope))} · BSB" data-tr="BSB">
              <div class="passage-strip-body">#{body}</div>
            </section>
            """
          end

        _ ->
          ""
      end
    else
      ""
    end
  end

  def passage_strip_html(_), do: ""

  defp row_verse_num(row) when is_map(row) do
    case row["v"] || row["verse"] do
      n when is_integer(n) ->
        n

      n when is_binary(n) ->
        case Integer.parse(n) do
          {i, _} -> i
          :error -> nil
        end

      _ ->
        nil
    end
  end

  defp related_html(pack_dir, scope, base) do
    notes = Note.list(pack_dir)
    a_int = Tree.scope_interval(scope)

    buckets =
      Enum.reduce(notes, %{contains: [], within: [], overlaps: []}, fn n, acc ->
        slug = get_in(n, ["scope", "slug"])

        if slug == scope.slug do
          acc
        else
          case Scope.parse(get_in(n, ["scope", "osis"]) || slug) do
            nil ->
              acc

            other ->
              case Tree.relate_intervals(a_int, Tree.scope_interval(other)) do
                :contains -> update_in(acc.contains, &[{other, n} | &1])
                :within -> update_in(acc.within, &[{other, n} | &1])
                :overlaps -> update_in(acc.overlaps, &[{other, n} | &1])
                _ -> acc
              end
          end
        end
      end)

    [
      related_section(
        "contains",
        "Within",
        "Notes on passages inside #{Scope.display(scope)}",
        Enum.reverse(buckets.contains),
        base
      ),
      related_section(
        "within",
        "Part of",
        "Broader passages this note sits in",
        Enum.reverse(buckets.within),
        base
      ),
      related_section(
        "overlaps",
        "Overlaps",
        "Ranges that partially overlap this note",
        Enum.reverse(buckets.overlaps),
        base
      )
    ]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n")
  end

