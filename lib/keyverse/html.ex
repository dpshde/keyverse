  defp render_home_tree_node(node, depth, base) do
    kids = Map.get(node, :children) || []
    has_kids = kids != []

    {id, note_href, read_href, ref, time_iso, sub, is_chapter} =
      case node do
        %{kind: :folder} = n ->
          c = n[:count] || Tree.count_tree_notes(n)
          sub = "#{c} note" <> if(c == 1, do: "", else: "s")

          {
            "folder:#{n.slug}",
            "#{base}/note/#{n.slug}",
            "#{base}/read/#{n.slug}",
            n.label,
            n.updated_at,
            sub,
            true
          }

        %{kind: :note, entry: entry} ->
          scope = entry.scope
          note = entry.note

          {
            "note:#{scope.slug}",
            "#{base}/note/#{scope.slug}",
            "#{base}/read/#{scope.slug}",
            Scope.display(scope),
            note["updated_at"],
            Tree.excerpt(note),
            scope.kind == "chapter"
          }
      end

    note_count =
      case node do
        %{kind: :folder} = n -> n[:count] || Tree.count_tree_notes(n)
        _ -> Tree.count_tree_notes(node)
      end

    row_cls =
      [
        "note-row",
        if(match?(%{kind: :folder}, node), do: "is-folder", else: nil),
        if(is_chapter, do: "is-chapter", else: nil),
        if(has_kids, do: "has-kids", else: nil),
        # Leaf notes are content cards (mobile home card parity)
        if(!has_kids, do: "is-note", else: nil)
      ]
      |> Enum.reject(&is_nil/1)
      |> Enum.join(" ")

    # Structure: no left chevron. Trailing count pill (collapsed) / quiet count
    # (expanded). Leaf notes keep edit/read chrome.
    meta =
      if has_kids do
        count_lbl = "#{note_count} note" <> if(note_count == 1, do: "", else: "s")

        """
        <span class="nt-meta">
          <span class="nt-count" aria-hidden="true" title="#{esc(count_lbl)}">#{note_count}</span>
        </span>
        """
      else
        """
        <span class="nt-meta">
          <a class="nt-act nt-open" href="#{esc(note_href)}" title="Open note" aria-label="Open note">#{@nt_icon_edit}</a>
          <a class="nt-act nt-read" href="#{esc(read_href)}" title="Read" aria-label="Read">#{@nt_icon_read}</a>
