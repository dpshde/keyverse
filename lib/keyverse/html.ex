  def page(title, body, opts \\ []) do
    base = Keyword.get(opts, :base, "")
    man_scope = Keyword.get(opts, :manifest_scope, base)

    man_path =
      if man_scope == "", do: "/manifest.webmanifest", else: "#{man_scope}/manifest.webmanifest"

    pwa_head = static_text("pwa-head.html")
    fathom = fathom_tag()

    """
    <!doctype html><html lang="en"><head><meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
    <title>#{esc(title)}</title>
    #{pwa_head}
    <link rel="manifest" href="#{esc(man_path)}">
    <link rel="stylesheet" href="/app.css">
    <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@phosphor-icons/web@2.1.2/src/regular/style.css" crossorigin="anonymous">
    <script src="/platform.js"></script>
    <script>window.BASE=#{Jason.encode!(base)};var BASE=window.BASE;</script>
    <script src="/crypto.js"></script>
    <script>if(window.VP_CRYPTO)VP_CRYPTO.ingestHash();</script>
    #{fathom}
    </head><body>#{body}
    <script src="/pwa-boot.js"></script>
    </body></html>
    """
  end

  defp static_text(name) do
    path = Path.join(Config.static_dir(), name)

    case File.read(path) do
      {:ok, body} ->
        body
        # Extractor banners are /* … */ — invalid as HTML and paint as page text if inlined in <head>.
        |> String.replace(~r/\A\s*\/\*[\s\S]*?\*\/\s*/, "")
        |> String.replace(
          ~r/\n\/\* generated by scripts\/extract_client_js\.mjs[\s\S]*?\*\/\n/,
          "\n"
        )

      _ ->
        ""
    end
  end

  defp fathom_tag do
    site = Config.fathom_site()

    if site == "" do
      ""
    else
      ~s(<script src="https://cdn.usefathom.com/script.js" data-site="#{esc(site)}" defer></script>)
    end
  end

