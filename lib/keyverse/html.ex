  @doc """
  Build reader payload for SSR and `GET /api/read/:slug`.
  Returns `{:ok, map}` or `{:error, reason}`.
  """
  def build_read_bundle(pack_dir, scope, base) do
    book = scope.parsed.book
    chapter = scope.parsed.chapter
    chapter_scope = Scope.parse("#{book}.#{chapter}")
    display = if chapter_scope, do: Scope.display(chapter_scope), else: Scope.display(scope)

    text_task = Task.async(fn -> Keyverse.TextCache.get_chapter(book, chapter) end)
    notes_task = Task.async(fn -> Note.list_for_chapter(pack_dir, book, chapter) end)
    text_result = Task.await(text_task, 15_000)
    notes = Task.await(notes_task, 15_000)

    case text_result do
      {:error, reason} ->
        {:error, reason}

      {:ok, text} ->
        hl =
          if scope.kind == "chapter" do
            nil
          else
            Tree.scope_interval(scope)
          end

        verse_notes = %{}
        range_notes = %{}
        range_cover = MapSet.new()
        chapter_note = nil

        {verse_notes, range_notes, range_cover, chapter_note} =
          Enum.reduce(notes, {verse_notes, range_notes, range_cover, chapter_note}, fn note,
                                                                                       acc ->
            {vn, rn, rc, cn} = acc

            other =
              Scope.parse(get_in(note, ["scope", "osis"]) || get_in(note, ["scope", "slug"]))

            cond do
              is_nil(other) ->
                acc

              other.parsed.book != book ->
                acc

              other.parsed.chapter != chapter ->
                acc

              other.kind == "chapter" ->
                {vn, rn, rc, note}

              other.kind == "verse" ->
                {Map.put(vn, other.parsed.verse, note), rn, rc, cn}

              true ->
                start_v = other.parsed.verse
                end_v = other.parsed.verse_end || start_v
                list = Map.get(rn, end_v, []) ++ [%{note: note, scope: other}]
                rn = Map.put(rn, end_v, list)
                rc = Enum.reduce(start_v..end_v, rc, &MapSet.put(&2, &1))
                {vn, rn, rc, cn}
            end
          end)

        seed = %{}

        seed =
          if chapter_note && not Note.encrypted?(chapter_note) && chapter_note["blocks"] do
            Map.put(seed, chapter_scope.slug, chapter_note["blocks"])
          else
            seed
          end

        {rows, seed} =
          Enum.reduce(text["verses"] || [], {"", seed}, fn vrow, {html, seed} ->
            v = vrow["v"]
            t = vrow["text"] || ""
            note = Map.get(verse_notes, v)
            ranges = Map.get(range_notes, v, [])
            in_hl = hl && Tree.pos(chapter, v) >= hl.s && Tree.pos(chapter, v) <= hl.e
            slug = "#{String.downcase(to_string(book))}.#{chapter}.#{v}"

            seed =
              if note && not Note.encrypted?(note) && note["blocks"] do
                Map.put(seed, slug, note["blocks"])
              else
                seed
              end

            seed =
              Enum.reduce(ranges, seed, fn e, s ->
                if not Note.encrypted?(e.note),
                  do: Map.put(s, e.scope.slug, e.note["blocks"] || []),
                  else: s
              end)

            v_scope = Scope.parse(slug)

            has_verse =
              note &&
                (Note.encrypted?(note) ||
                   Enum.any?(note["blocks"] || [], fn b ->
                     String.trim(to_string(b["text"] || "")) != ""
                   end))

            has_notes = has_verse || ranges != [] || MapSet.member?(range_cover, v)

            range_html =
              Enum.map_join(ranges, "\n", fn e ->
                reader_note_html(e.scope, e.note, base, true)
              end)

            verse_html =
              if has_verse, do: reader_note_html(v_scope, note, base, true), else: ""

            notes_inner = ""

            notes_inner =
              if range_html != "" do
                notes_inner <>
                  ~s(<div class="note-group passage">) <>
                  if(verse_html == "",
                    do: "",
                    else: ~s(<div class="note-group-title">Passage</div>)
                  ) <>
                  range_html <> ~s(</div>)
              else
                notes_inner
              end

            notes_inner =
              if verse_html != "" do
                notes_inner <>
                  ~s(<div class="note-group verse-local">) <>
                  if(ranges != [],
                    do: ~s(<div class="note-group-title">This verse</div>),
                    else: ""
                  ) <>
                  verse_html <> ~s(</div>)
              else
                notes_inner
              end

            v_cls =
              [
                "verse",
                if(in_hl, do: "hl", else: nil),
                if(has_notes, do: "has-notes", else: nil),
                if(has_verse, do: "has-verse-note", else: nil)
              ]
              |> Enum.reject(&is_nil/1)
              |> Enum.join(" ")

            row = """
            <div class="#{v_cls}" data-slug="#{esc(slug)}" data-v="#{v}" id="v#{v}">
              <p class="vtext"><sup>#{v}</sup>#{esc(t)}<span class="vstatus"></span></p>
              <div class="vnotes">#{notes_inner}</div>
            </div>
            """

            {html <> row, seed}
          end)

        chapter_note_html =
          if chapter_note do
            ~s(<div class="chapter-note" id="chapter-note">#{reader_note_html(chapter_scope, chapter_note, base, false)}</div>)
          else
            ~s(<div class="chapter-note" id="chapter-note" hidden></div>)
          end

        prev = Scope.neighbor_chapter(chapter_scope || scope, -1)
        next = Scope.neighbor_chapter(chapter_scope || scope, 1)

        meta = %{
          slug: (chapter_scope || scope).slug,
          display: display,
          book: book,
          chapter: chapter,
          kind: scope.kind,
          hl_slug: scope.slug,
          prev_slug: if(prev, do: prev.slug, else: nil),
          next_slug: if(next, do: next.slug, else: nil),
          chapter_note_slug: if(chapter_scope, do: chapter_scope.slug, else: nil)
        }

        {:ok,
         %{
           meta: meta,
           seed: seed,
           text: %{
             "translation" => text["translation"] || "BSB",
             "book" => book,
             "chapter" => chapter,
             "verses" => text["verses"] || []
           },
           html: %{
             chapter_note: chapter_note_html,
             verses: rows
           }
         }}
    end
  end

